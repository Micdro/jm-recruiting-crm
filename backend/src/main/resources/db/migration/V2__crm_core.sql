-- Turns the starter schema into the full CRM: users, structured outreach, searches,
-- candidates, pipeline, placements and an activity log. Existing rows are kept.

-- Users ---------------------------------------------------------------------

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email));

-- Companies -----------------------------------------------------------------

ALTER TABLE company ADD COLUMN IF NOT EXISTS focus VARCHAR(500);
ALTER TABLE company ADD COLUMN IF NOT EXISTS owner_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL;
ALTER TABLE company ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now();
ALTER TABLE company ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now();

-- Free-text statuses become the fixed set the app uses.
UPDATE company SET status = CASE
    WHEN status IS NULL OR btrim(status) = '' THEN 'TARGET'
    WHEN upper(btrim(status)) IN ('TARGET', 'PROSPECTING', 'IN_CONVERSATION', 'CLIENT', 'NOT_A_FIT') THEN upper(btrim(status))
    WHEN lower(status) LIKE '%client%' THEN 'CLIENT'
    WHEN lower(status) LIKE '%fit%' OR lower(status) LIKE '%disqualif%' THEN 'NOT_A_FIT'
    WHEN lower(status) LIKE '%conversation%' OR lower(status) LIKE '%meeting%' OR lower(status) LIKE '%talk%' THEN 'IN_CONVERSATION'
    WHEN lower(status) LIKE '%prospect%' OR lower(status) LIKE '%outreach%' OR lower(status) LIKE '%contact%' THEN 'PROSPECTING'
    ELSE 'TARGET'
END;

ALTER TABLE company ALTER COLUMN status TYPE VARCHAR(30);
ALTER TABLE company ALTER COLUMN status SET NOT NULL;

CREATE INDEX IF NOT EXISTS ix_company_name ON company (lower(name));

-- Contacts ------------------------------------------------------------------

ALTER TABLE contact RENAME COLUMN next_follow_up_date TO next_action_date;

ALTER TABLE contact ADD COLUMN status VARCHAR(30) NOT NULL DEFAULT 'NEW';
ALTER TABLE contact ADD COLUMN next_action_type VARCHAR(20);
ALTER TABLE contact ADD COLUMN touch_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE contact ADD COLUMN phone VARCHAR(50);
ALTER TABLE contact ADD COLUMN owner_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL;
ALTER TABLE contact ADD COLUMN created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now();
ALTER TABLE contact ADD COLUMN updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now();

ALTER TABLE contact ALTER COLUMN notes TYPE VARCHAR(2000);
ALTER TABLE contact ALTER COLUMN linkedin_url TYPE VARCHAR(500);

-- Keep the old free-text relationship status in the notes before dropping the column.
UPDATE contact
SET notes = left(concat_ws(E'\n', notes, 'Relationship status: ' || relationship_status), 2000)
WHERE relationship_status IS NOT NULL AND btrim(relationship_status) <> '';

UPDATE contact SET name = 'Unnamed contact' WHERE name IS NULL OR btrim(name) = '';
ALTER TABLE contact ALTER COLUMN name SET NOT NULL;
ALTER TABLE contact DROP COLUMN relationship_status;

CREATE INDEX ix_contact_company ON contact (company_id);
CREATE INDEX ix_contact_next_action ON contact (next_action_date);
CREATE INDEX ix_contact_email ON contact (lower(email));

-- Searches (client engagements) -------------------------------------------------

CREATE TABLE job_search (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id             BIGINT       NOT NULL REFERENCES company (id),
    hiring_manager_id      BIGINT REFERENCES contact (id) ON DELETE SET NULL,
    title                  VARCHAR(255) NOT NULL,
    track                  VARCHAR(40)  NOT NULL,
    status                 VARCHAR(20)  NOT NULL,
    engagement_type        VARCHAR(20)  NOT NULL,
    fee_percent            NUMERIC(5, 2),
    base_min               INTEGER,
    base_max               INTEGER,
    location               VARCHAR(255),
    work_model             VARCHAR(20),
    timeline               VARCHAR(30),
    opened_date            DATE,
    production_outcome     VARCHAR(2000),
    technical_scope        VARCHAR(2000),
    accountability         VARCHAR(2000),
    regulatory_constraints VARCHAR(2000),
    notes                  VARCHAR(2000),
    owner_id               BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_job_search_company ON job_search (company_id);

-- Candidates ----------------------------------------------------------------

CREATE TABLE candidate (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL,
    email                VARCHAR(255),
    phone                VARCHAR(50),
    linkedin_url         VARCHAR(500),
    location             VARCHAR(255),
    current_title        VARCHAR(255),
    current_company      VARCHAR(255),
    track                VARCHAR(40),
    status               VARCHAR(20)  NOT NULL,
    source               VARCHAR(20),
    regulated_experience BOOLEAN      NOT NULL DEFAULT FALSE,
    comp_expectation     VARCHAR(255),
    resume_url           VARCHAR(500),
    production_evidence  VARCHAR(4000),
    last_contacted_date  DATE,
    next_action_date     DATE,
    next_action_type     VARCHAR(20),
    notes                VARCHAR(2000),
    owner_id             BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_candidate_email ON candidate (lower(email));
CREATE INDEX ix_candidate_next_action ON candidate (next_action_date);

-- Pipeline: a candidate's progress in one search ---------------------------------

CREATE TABLE pipeline_entry (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id        BIGINT      NOT NULL REFERENCES job_search (id) ON DELETE CASCADE,
    candidate_id     BIGINT      NOT NULL REFERENCES candidate (id) ON DELETE CASCADE,
    stage            VARCHAR(30) NOT NULL,
    rationale        VARCHAR(2000),
    stage_changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ux_pipeline_search_candidate UNIQUE (search_id, candidate_id)
);

CREATE INDEX ix_pipeline_candidate ON pipeline_entry (candidate_id);

-- Placements and fees ---------------------------------------------------------

CREATE TABLE placement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_id          BIGINT      NOT NULL REFERENCES job_search (id),
    candidate_id       BIGINT      NOT NULL REFERENCES candidate (id),
    start_date         DATE,
    base_salary        INTEGER,
    fee_percent        NUMERIC(5, 2),
    fee_amount         NUMERIC(12, 2),
    invoice_status     VARCHAR(20) NOT NULL,
    invoice_date       DATE,
    paid_date          DATE,
    guarantee_end_date DATE,
    notes              VARCHAR(2000),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ux_placement_search_candidate UNIQUE (search_id, candidate_id)
);

-- Activity log: touches, replies, meetings, notes and automatic status changes ------

CREATE TABLE activity (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(20) NOT NULL,
    touch        BOOLEAN     NOT NULL DEFAULT FALSE,
    summary      VARCHAR(2000),
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id      BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    company_id   BIGINT REFERENCES company (id) ON DELETE CASCADE,
    contact_id   BIGINT REFERENCES contact (id) ON DELETE CASCADE,
    candidate_id BIGINT REFERENCES candidate (id) ON DELETE CASCADE,
    search_id    BIGINT REFERENCES job_search (id) ON DELETE CASCADE
);

CREATE INDEX ix_activity_contact ON activity (contact_id);
CREATE INDEX ix_activity_candidate ON activity (candidate_id);
CREATE INDEX ix_activity_search ON activity (search_id);
CREATE INDEX ix_activity_company ON activity (company_id);
CREATE INDEX ix_activity_occurred ON activity (occurred_at);
CREATE INDEX ix_activity_user_touch ON activity (user_id, occurred_at) WHERE touch;
