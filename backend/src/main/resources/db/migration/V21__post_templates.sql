-- Saved post templates for Marketing: a title, the post's text, notes, theme and where it goes,
-- picked from a list when adding or writing a post. Shared with the team and synced like the
-- rest. Text is encrypted by the app.
CREATE TABLE post_template (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT        NOT NULL,
    title      TEXT,
    body       TEXT,
    notes      TEXT,
    theme      VARCHAR(30) NOT NULL DEFAULT 'OTHER',
    account    VARCHAR(20) NOT NULL DEFAULT 'PERSONAL',
    owner_id   BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON post_template
    FOR EACH ROW EXECUTE FUNCTION sync_track();

-- A computer still on an older version skips templates made on an updated one. Read every
-- computer's sync files once more, so those templates arrive; what's already here is left as it is.
UPDATE sync_peer_state SET folder_instance = NULL;
