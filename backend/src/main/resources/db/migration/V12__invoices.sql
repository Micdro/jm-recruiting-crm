-- The firm's own details for invoices (name, address, payment instructions), shared by the team.
-- One row per setting; values are encrypted by the app.
CREATE TABLE firm_setting (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL UNIQUE,
    value      TEXT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON firm_setting
    FOR EACH ROW EXECUTE FUNCTION sync_track();
