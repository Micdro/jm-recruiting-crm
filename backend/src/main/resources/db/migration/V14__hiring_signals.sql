-- Hiring signals: open forward deployed and AI platform roles on the public job boards (Greenhouse,
-- Lever, Ashby) of companies in the CRM.
--
-- Which board a company uses, whether someone confirmed it, and when the team last reviewed its
-- signals are shared like the rest of the company. The postings themselves are a cache that each
-- computer fetches for itself, so job_posting and job_board_check are not synced.

ALTER TABLE company ADD COLUMN job_board_provider VARCHAR(20);
-- Encrypted by the app: the board's name identifies the company.
ALTER TABLE company ADD COLUMN job_board_token TEXT;
-- False when the board was found automatically and nobody has checked it yet.
ALTER TABLE company ADD COLUMN job_board_confirmed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE company ADD COLUMN signals_reviewed_at TIMESTAMP(6) WITH TIME ZONE;

-- Matching open roles on each company's board. Title, location and link are encrypted by the app.
CREATE TABLE job_posting (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    BIGINT       NOT NULL REFERENCES company (id) ON DELETE CASCADE,
    provider      VARCHAR(20)  NOT NULL,
    external_id   VARCHAR(100) NOT NULL,
    title         TEXT         NOT NULL,
    location      TEXT,
    url           TEXT,
    track         VARCHAR(20)  NOT NULL,
    published_at  TIMESTAMP(6) WITH TIME ZONE,
    first_seen_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ux_job_posting UNIQUE (company_id, provider, external_id)
);

-- When this computer last read each company's board, how many roles it had in all, what went
-- wrong if it couldn't be read, and when it last looked for a board automatically.
CREATE TABLE job_board_check (
    company_id  BIGINT PRIMARY KEY REFERENCES company (id) ON DELETE CASCADE,
    checked_at  TIMESTAMP(6) WITH TIME ZONE,
    open_roles  INTEGER,
    error       VARCHAR(500),
    searched_at TIMESTAMP(6) WITH TIME ZONE
);
