-- Resumes and other files kept on a candidate. The row (name, type, size) is shared and synced like
-- the rest; the file itself is kept apart in file_blob, encrypted by the app with the CRM key, and
-- travels between computers as its own file in the sync folder.
CREATE TABLE candidate_file (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id   BIGINT       NOT NULL REFERENCES candidate (id) ON DELETE CASCADE,
    file_name      TEXT         NOT NULL,
    content_type   VARCHAR(100) NOT NULL,
    size_bytes     BIGINT       NOT NULL,
    blob_key       VARCHAR(32)  NOT NULL,
    uploaded_by_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_candidate_file_candidate ON candidate_file (candidate_id);
CREATE INDEX ix_candidate_file_blob ON candidate_file (blob_key);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON candidate_file
    FOR EACH ROW EXECUTE FUNCTION sync_track();

-- The encrypted contents, by key. Not synced row by row: each computer fetches the files it lacks.
CREATE TABLE file_blob (
    blob_key   VARCHAR(32) PRIMARY KEY,
    content    BYTEA       NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Older versions skipped records of tables they didn't know yet (message templates, say). Read
-- every computer's sync files once more, so anything skipped arrives; what's already here is
-- left as it is.
UPDATE sync_peer_state SET folder_instance = NULL;
