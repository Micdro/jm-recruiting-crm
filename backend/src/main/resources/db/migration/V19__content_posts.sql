-- Marketing: the team's LinkedIn posts, from idea to posted, and what each one led to.
-- One row per post. An idea is a post with no date yet. Posting stays manual: the team writes and
-- plans here, then posts on LinkedIn themselves and records the link and results.
-- Shared with the team and synced like the rest. Text is encrypted by the app.
CREATE TABLE content_post (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         TEXT        NOT NULL,
    body          TEXT,
    notes         TEXT,
    theme         VARCHAR(30) NOT NULL DEFAULT 'OTHER',
    account       VARCHAR(20) NOT NULL DEFAULT 'PERSONAL',
    status        VARCHAR(20) NOT NULL DEFAULT 'IDEA',
    planned_for   DATE,
    posted_on     DATE,
    post_url      TEXT,
    impressions   INTEGER,
    reactions     INTEGER,
    comments      INTEGER,
    conversations INTEGER,
    owner_id      BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX content_post_planned_for ON content_post (planned_for);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON content_post
    FOR EACH ROW EXECUTE FUNCTION sync_track();
