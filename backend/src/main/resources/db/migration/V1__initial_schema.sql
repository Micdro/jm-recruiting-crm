-- The schema as it existed before Flyway (when Hibernate created it with ddl-auto=update).
-- Existing databases are baselined at version 1, so this script only runs on new databases.

CREATE TABLE IF NOT EXISTS company (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    website          VARCHAR(500),
    location         VARCHAR(255),
    company_size     VARCHAR(100),
    status           VARCHAR(100),
    linkedin_profile VARCHAR(500),
    notes            VARCHAR(2000)
);

CREATE TABLE IF NOT EXISTS contact (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255),
    title               VARCHAR(255),
    email               VARCHAR(255),
    linkedin_url        VARCHAR(255),
    relationship_status VARCHAR(255),
    last_contacted_date DATE,
    next_follow_up_date DATE,
    notes               VARCHAR(255),
    company_id          BIGINT NOT NULL REFERENCES company (id)
);
