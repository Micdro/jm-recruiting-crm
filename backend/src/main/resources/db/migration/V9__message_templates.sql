-- Saved messages for the outreach sequence: what to send on LinkedIn or by email at each touch.
-- Shared with the team and synced like the rest. Text is encrypted by the app.
CREATE TABLE message_template (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT        NOT NULL,
    channel    VARCHAR(20) NOT NULL,
    touch      INTEGER,
    subject    TEXT,
    body       TEXT        NOT NULL,
    owner_id   BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON message_template
    FOR EACH ROW EXECUTE FUNCTION sync_track();
