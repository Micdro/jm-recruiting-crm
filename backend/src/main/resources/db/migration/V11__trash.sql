-- Deleted records wait here for 30 days, with everything that was removed with them (a contact's
-- notes and touches, a candidate's pipeline and files), so any computer can put them back.
-- Shared and synced like the rest. Name, detail and contents are encrypted by the app.
CREATE TABLE trash_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(30) NOT NULL,
    record_id     BIGINT      NOT NULL,
    label         TEXT        NOT NULL,
    detail        TEXT,
    contents      TEXT        NOT NULL,
    -- Files the deleted records used, kept until the item is restored or purged.
    blob_keys     TEXT,
    -- Where the record opens once restored.
    path          VARCHAR(200) NOT NULL,
    deleted_by_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    deleted_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_trash_item_record ON trash_item (kind, record_id);
CREATE INDEX ix_trash_item_deleted_at ON trash_item (deleted_at);

CREATE TRIGGER sync_track AFTER INSERT OR UPDATE OR DELETE ON trash_item
    FOR EACH ROW EXECUTE FUNCTION sync_track();
